"""Regenerate db/schema.sql from the models:  python -m scripts.export_schema"""
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from app import models  # noqa: F401
from app.db import Base

out = ["-- PostgreSQL schema. GENERATED by scripts/export_schema.py. All times UTC.\n"]
for table in Base.metadata.sorted_tables:
    out.append(str(CreateTable(table).compile(dialect=postgresql.dialect())).strip() + ";\n")
    for idx in table.indexes:
        out.append(str(CreateIndex(idx).compile(dialect=postgresql.dialect())).strip() + ";")
    out.append("")
out.append("-- Optional later (faster fuzzy search at scale):\n-- CREATE EXTENSION pg_trgm;\n"
           "-- CREATE INDEX ix_products_name_trgm ON products USING gin (product_name gin_trgm_ops);")
open("db/schema.sql", "w").write("\n".join(out) + "\n")
print("wrote db/schema.sql")
